"""Context documentation rendering for Markdown and optional PDF output."""

from datetime import datetime
from io import StringIO
from pathlib import Path
import re
from xml.sax.saxutils import escape

from ruamel.yaml import YAML
from ruamel.yaml.error import YAMLError

from konman import __version__
from konman.engine import ContextEngine
from konman.storage import atomic_write_bytes, atomic_write_text


_NODE_FIELDS = {
    "requirements": (
        "id", "statement", "kind", "priority", "source", "why",
        "derives_from", "status", "added", "evidence", "evidence_ids", "related_nodes", "review",
        "rejection_reason",
    ),
    "decisions": (
        "id", "chosen", "mode", "decided", "considered", "tradeoff",
        "reason", "status", "evidence", "evidence_ids", "related_nodes", "review", "rejection_reason",
    ),
    "boundaries": (
        "id", "path", "constrains", "risks", "questions", "rule", "why", "status",
        "evidence", "evidence_ids", "review", "rejection_reason",
    ),
    "objects": ("id", "name", "kind", "description", "properties", "evidence", "related_nodes", "status"),
    "evidence": (
        "id", "source_type", "locator", "excerpt", "captured_by",
        "captured_at", "related_nodes", "status",
    ),
    "changes": (
        "id", "summary", "commit", "author", "changed_at", "files",
        "implements", "affects", "evidence", "verification", "related_nodes", "status",
    ),
    "questions": (
        "id", "question", "status", "answer", "owner", "requirements",
        "decisions", "objects", "evidence", "resolution", "related_nodes",
    ),
    "risks": (
        "id", "statement", "likelihood", "impact", "mitigation", "status",
        "requirements", "decisions", "changes", "evidence", "resolution", "related_nodes",
    ),
}


def _read_yaml(path: Path):
    try:
        return YAML().load(path.read_text(encoding="utf-8"))
    except (OSError, YAMLError) as error:
        raise ValueError(f"Cannot read context data from {path}: {error}") from error


def _dump_yaml(data) -> str:
    serialized = StringIO()
    yaml = YAML()
    yaml.default_flow_style = False
    yaml.dump(data, serialized)
    return serialized.getvalue().rstrip()


def _yaml_files(directory: Path, fields: tuple[str, ...]) -> list[dict]:
    if not directory.is_dir():
        return []
    records = []
    for path in sorted(directory.glob("*.yaml")):
        node = _read_yaml(path)
        if not isinstance(node, dict):
            raise ValueError(f"Expected a YAML mapping in {path}.")
        records.append({key: node[key] for key in fields if key in node})
    return records


def _read_boundaries(path: Path) -> list[dict]:
    if not path.exists():
        return []
    data = _read_yaml(path) or []
    data = [data] if isinstance(data, dict) else data
    if not isinstance(data, list) or any(not isinstance(item, dict) for item in data):
        raise ValueError(f"Expected a YAML list of mappings in {path}.")
    return [
        {key: item[key] for key in _NODE_FIELDS["boundaries"] if key in item}
        for item in data
    ]


def _fence(text: str) -> str:
    longest = max((len(match.group(0)) for match in re.finditer(r"`+", text)), default=0)
    return "`" * max(3, longest + 1)


def _yaml_block(node: dict) -> str:
    body = _dump_yaml(node)
    fence = _fence(body)
    return f"{fence}yaml\n{body}\n{fence}"


def _node_section(title: str, nodes: list[dict], name_field: str) -> list[str]:
    lines = [f"## {title}", ""]
    if not nodes:
        return lines + ["No records.", ""]
    for node in nodes:
        lines.extend([f"### {node.get('id') or node.get(name_field) or title}", "", _yaml_block(node), ""])
    return lines


def render_context_markdown(engine: ContextEngine) -> str:
    """Render repository context and specifications without raw captures or credentials."""
    if not engine.ctx_dir.is_dir():
        raise ValueError(f"No .context directory found in {engine.base_dir}; run `konman init` first.")

    lines = [
        f"# Project Context and Specifications: {engine.base_dir.name}",
        "",
        f"Generated by Konman {__version__} on {datetime.now().astimezone().isoformat(timespec='minutes')}.",
        "",
        "## Project Overview",
        "",
    ]
    project_path = engine.ctx_dir / "project.md"
    if project_path.is_file():
        try:
            overview = project_path.read_text(encoding="utf-8").strip()
        except OSError as error:
            raise ValueError(f"Cannot read project overview from {project_path}: {error}") from error
        lines.extend([overview or "No project overview recorded.", ""])
    else:
        lines.extend(["No project overview recorded in `.context/project.md`.", ""])

    lines.extend(_node_section(
        "Requirements",
        _yaml_files(engine.ctx_dir / "requirements", _NODE_FIELDS["requirements"]),
        "statement",
    ))
    lines.extend(_node_section(
        "Decisions",
        _yaml_files(engine.ctx_dir / "decisions", _NODE_FIELDS["decisions"]),
        "chosen",
    ))
    boundary_nodes = _read_boundaries(engine.ctx_dir / "boundaries.yaml")
    boundary_nodes.sort(key=lambda node: str(node.get("id") or node.get("path") or ""))
    lines.extend(_node_section("Protected Boundaries", boundary_nodes, "path"))
    for kind, title, label in (
        ("objects", "Components", "name"),
        ("evidence", "Sources", "excerpt"),
        ("changes", "Changes", "summary"),
        ("questions", "Questions", "question"),
        ("risks", "Risks", "statement"),
    ):
        nodes = _yaml_files(engine.ctx_dir / kind, _NODE_FIELDS[kind])
        lines.extend(_node_section(title, nodes, label))

    state_path = engine.ctx_dir / "state" / "current.yaml"
    lines.extend(["## Current State", ""])
    if state_path.is_file():
        state = _read_yaml(state_path)
        lines.extend([_yaml_block({"current_state": state}), ""])
    else:
        lines.extend(["No current state recorded.", ""])

    legacy_question_files = []
    question_dir = engine.ctx_dir / "questions"
    if question_dir.is_dir():
        legacy_question_files = sorted(
            path for path in question_dir.iterdir()
            if path.is_file() and path.suffix.lower() == ".md"
        )
    if legacy_question_files:
        lines.extend(["## Legacy Question Notes", ""])
        for path in legacy_question_files:
            lines.extend([f"### {path.name}", ""])
            try:
                text = path.read_text(encoding="utf-8").strip()
            except OSError as error:
                raise ValueError(f"Cannot read question from {path}: {error}") from error
            lines.extend([text or "Empty question document.", ""])

    return "\n".join(lines).rstrip() + "\n"


def write_markdown(markdown: str, output_path: Path) -> None:
    atomic_write_text(output_path, markdown)


def write_pdf(markdown: str, output_path: Path) -> None:
    """Render the generated Markdown subset to PDF using the optional ReportLab extra."""
    try:
        from reportlab.lib import colors
        from reportlab.lib.enums import TA_LEFT
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
        from reportlab.lib.units import mm
        from reportlab.platypus import (
            Paragraph,
            Preformatted,
            SimpleDocTemplate,
            Spacer,
        )
    except ImportError as error:
        raise RuntimeError(
            'PDF output requires ReportLab. Install it with `pip install "konman[pdf]"`.'
        ) from error

    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle(
        name="KonmanCode",
        parent=styles["Code"],
        fontName="Courier",
        fontSize=7.5,
        leading=9,
        leftIndent=6,
        rightIndent=6,
        backColor=colors.whitesmoke,
        borderColor=colors.lightgrey,
        borderWidth=0.5,
        borderPadding=5,
        spaceBefore=4,
        spaceAfter=8,
        splitLongWords=1,
    ))
    styles.add(ParagraphStyle(
        name="KonmanBody",
        parent=styles["BodyText"],
        alignment=TA_LEFT,
        spaceAfter=6,
        splitLongWords=1,
    ))
    story = []
    code_lines = []
    in_code = False
    code_fence = ""
    for line in markdown.splitlines():
        opening_fence = re.match(r"(`{3,})", line)
        if not in_code and opening_fence:
            code_fence = opening_fence.group(1)
            in_code = True
            continue
        if in_code and line.startswith(code_fence):
            story.append(Preformatted("\n".join(code_lines), styles["KonmanCode"]))
            code_lines = []
            code_fence = ""
            in_code = False
            continue
        if in_code:
            code_lines.append(line)
        elif not line.strip():
            story.append(Spacer(1, 3))
        elif line.startswith("# "):
            story.append(Paragraph(escape(line[2:]), styles["Title"]))
        elif line.startswith("## "):
            story.append(Paragraph(escape(line[3:]), styles["Heading1"]))
        elif line.startswith("### "):
            story.append(Paragraph(escape(line[4:]), styles["Heading2"]))
        elif line.startswith("- "):
            story.append(Paragraph(f"&bull; {escape(line[2:])}", styles["KonmanBody"]))
        else:
            story.append(Paragraph(escape(line), styles["KonmanBody"]))
    if in_code:
        story.append(Preformatted("\n".join(code_lines), styles["KonmanCode"]))

    from io import BytesIO

    output = BytesIO()
    document = SimpleDocTemplate(
        output,
        pagesize=A4,
        rightMargin=18 * mm,
        leftMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
        title="Project Context and Specifications",
    )
    document.build(story)
    atomic_write_bytes(output_path, output.getvalue())
